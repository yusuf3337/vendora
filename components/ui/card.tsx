import * as React from "react";
import { cn } from "@/lib/utils";

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { hoverGlow?: boolean }
>(({ className, hoverGlow = false, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-3xl border border-zinc-200/80 bg-white/90 backdrop-blur-md text-zinc-900 shadow-sm transition-all duration-300",
      hoverGlow && "hover:border-accent/50 hover:shadow-lg hover:shadow-orange-500/10 hover:-translate-y-1",
      className
    )}
    {...props}
  />
));
Card.displayName = "Card";

